//! `cainary-tray/qml/dev/SampleView.js` is generated from the shared scenarios, so the QML
//! harness renders exactly what the Rust view builder produces. Regenerate it with
//! `UPDATE_SAMPLE_VIEW=1 cargo test -p cainary-tray-model --test sample_view`.

use std::fmt::Write;
use std::path::Path;

use cainary_tray_model::fixtures::scenarios;
use cainary_tray_model::{strings, view};
use serde_json::{Value, json};

const FILE: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../cainary-tray/qml/dev/SampleView.js"
);

fn render() -> String {
    let mut views = serde_json::Map::new();
    let mut statuses = serde_json::Map::new();
    let mut collectors = serde_json::Map::new();
    let mut list = Vec::new();
    let mut collector_settings = serde_json::Map::new();
    for s in scenarios() {
        list.push(
            json!({"name": s.name, "window": s.window, "selection": s.selection, "dark": s.dark}),
        );
        let built = view::build(
            &s.state,
            &s.settings,
            false,
            |_| "14:05".into(),
            |_, _| String::new(),
        );
        let mut view = serde_json::from_str::<Value>(&built).unwrap();
        sanitize_sample_paths(&mut view);
        views.insert(s.name.into(), view);
        if let Some(collector) = s.collector() {
            let mut collector = serde_json::from_str::<Value>(&collector).unwrap();
            sanitize_sample_paths(&mut collector);
            collectors.insert(s.name.into(), collector);
        }
        collector_settings.insert(
            s.name.into(),
            serde_json::to_value(&s.settings.collector).unwrap(),
        );
        let status = view::status(&s.state, |_| "14:05".into());
        statuses.insert(
            s.name.into(),
            json!({"busy": status.busy, "phase": status.phase, "lastChecked": status.last_checked}),
        );
    }
    let fixed = strings::static_json("0.0.0-sample", "sample", "2026-01-01");
    let mut js = String::from(
        ".pragma library\n\n\
         // Generated by tray-model/tests/sample_view.rs from fixtures::scenarios(); do not edit.\n\
         // Regenerate with UPDATE_SAMPLE_VIEW=1 cargo test -p cainary-tray-model --test sample_view.\n",
    );
    let pretty = |value: &Value| serde_json::to_string_pretty(value).unwrap();
    writeln!(js, "var scenarios = {};", pretty(&Value::Array(list))).unwrap();
    writeln!(js, "var variants = {};", pretty(&Value::Object(views))).unwrap();
    writeln!(js, "var statuses = {};", pretty(&Value::Object(statuses))).unwrap();
    writeln!(
        js,
        "var collectors = {};",
        pretty(&Value::Object(collectors))
    )
    .unwrap();
    writeln!(
        js,
        "var collectorSettingsData = {};",
        pretty(&Value::Object(collector_settings))
    )
    .unwrap();
    writeln!(js, "var staticData = {};", pretty(&fixed)).unwrap();
    js.push_str(
        "\nfunction variant(name) { return JSON.stringify(variants[name]); }\n\
         function status(name) { return JSON.stringify(statuses[name]); }\n\
         function staticJson() { return JSON.stringify(staticData); }\n\
         function collector(name) { return name in collectors ? JSON.stringify(collectors[name]) : \"\"; }\n\
         function collectorSettings(name) { return JSON.stringify(collectorSettingsData[name] || {}); }\n",
    );
    js
}

/// Keep generated UI samples from looking like real scan targets. Paths from runtime reports
/// are left untouched; this only edits the synthetic sample data rendered above.
fn sanitize_sample_paths(value: &mut Value) {
    match value {
        Value::String(text) => {
            *text = text
                .replace("~/.claude/", "~/claude-")
                .replace("/.claude/", "/claude-");
        }
        Value::Array(values) => values.iter_mut().for_each(sanitize_sample_paths),
        Value::Object(values) => values.values_mut().for_each(sanitize_sample_paths),
        _ => {}
    }
}

#[test]
fn sample_view_is_up_to_date() {
    let want = render();
    if std::env::var_os("UPDATE_SAMPLE_VIEW").is_some() {
        std::fs::write(FILE, &want).unwrap();
        return;
    }
    let have = std::fs::read_to_string(Path::new(FILE)).unwrap_or_default();
    assert!(
        have == want,
        "SampleView.js is stale: run with UPDATE_SAMPLE_VIEW=1 (cargo test -p cainary-tray-model --test sample_view)"
    );
}
